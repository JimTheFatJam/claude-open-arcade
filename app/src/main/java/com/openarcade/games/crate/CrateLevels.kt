package com.openarcade.games.crate

/**
 * Level packs in the usual text notation: # wall, space floor, . goal, $ crate, * crate on goal,
 * @ player, + player on goal. Every level was generated backwards from the solved position, so it
 * is solvable; the test suite re-solves each one.
 */
object CrateLevels {
    val packs: List<List<CrateLevel>> by lazy { listOf(easy, normal, hard).map { p -> p.map { CrateLevel(it) } } }

    private val easy = listOf(
        listOf("#######", "#  .\$@#", "# ### #", "#  .\$ #", "#######"),
        listOf("######", "#@   #", "# .\$ #", "# \$ .#", "######"),
        listOf("  #####", "###   #", "#@\$ # #", "# .   #", "### * #", "  #####"),
        listOf("########", "#@  #  #", "# \$.\$ .#", "#  #   #", "########"),
        listOf("########", "#@     #", "# #..# #", "#   \$\$ #", "###  ###", "  ####"),
        listOf("#########", "#   #   #", "# #\$  # #", "#  .#.  #", "## # #\$##", "#@\$.#.\$ #", "#       #", "#########"),
        listOf("#######", "#.  \$ #", "# ##@ #", "#   # #", "#.  \$ #", "#######"),
        listOf("#########", "#+\$ # \$.#", "#\$# # # #", "#       #", "# # # # #", "#.  # \$.#", "#########"),
    )
    private val normal = listOf(
        listOf("##########", "#  #     #", "# ..*# # #", "#    \$ # #", "##\$### # #", "#@       #", "##########"),
        listOf("##########", "#@   #   #", "# ## \$ # #", "# \$.#.   #", "##\$#  ## #", "#  . #.\$ #", "#   #    #", "##########"),
        listOf("#######", "#     #", "#\$#.#.#", "#  \$@\$#", "#.# # #", "#     #", "#######"),
        listOf("#######", "#@.   #", "# # # #", "#  .\$ #", "# #\$# #", "#  \$. #", "#######"),
        listOf(" ########", "##  #   #", "#@ .\$.\$ #", "# ##\$## #", "# \$. .  #", "##  #   #", " ########"),
        listOf("########", "#@  #  #", "# . .  #", "##\$### #", "# \$.\$  #", "#      #", "########"),
        listOf(" ########", " #   #@ #", "## # \$. #", "#  .\$## #", "# #  .\$ #", "#   #.\$ #", "#########"),
        listOf("#########", "#@  #   #", "# # * # #", "# \$. .\$ #", "# # * # #", "#   #   #", "#########"),
    )
    private val hard = listOf(
        listOf("########", "#@ #   #", "# \$. . #", "## \$#  #", " # . \$ #", " #######"),
        listOf("  #######", "###  #  #", "#@\$.    #", "# # ##. #", "# \$*  # #", "### #.\$ #", "  #     #", "  #######"),
        listOf("  ########", "###  #   #", "#@\$.   . #", "# ## # # #", "# \$. #*\$ #", "###     ##", "  #######"),
        listOf("##########", "#    #   #", "# . \$  . #", "### ## ###", "#   .\$\$* #", "#    #@  #", "##########"),
        listOf("###########", "#    #@   #", "# .  #\$ . #", "#  # \$ #  #", "## # * # ##", "#  \$ #  \$ #", "# .     . #", "###########"),
        listOf("##########", "#@  ##   #", "# .\$   . #", "#  # ##\$##", "## # \$.  #", "#  .\$#   #", "#    #####", "######"),
        listOf("#########", "#+  #  .#", "# \$\$#   #", "##     ##", "#  \$#   #", "#*  #  .#", "#########"),
        listOf(" #########", "##   #   #", "#@\$. \$ . #", "# #  # \$##", "#  . # * #", "##   #   #", " #########"),
    )
}
